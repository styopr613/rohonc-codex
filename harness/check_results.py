"""Verify the figures written in RESULTS.md prose against the results JSON.

The tables are generated by build_results.py and cannot drift. The prose is
written by hand and can. This checks every claim in it that carries a number.

Modelled on voynich-fingerprint's check_report.py, and for the same reason: a
document whose figures are not checked is a document whose figures are wrong.

    python check_results.py
"""
import json
import os
import sys

import corpus

WORK = os.path.join(corpus.ROOT, "work")
DOC = os.path.join(corpus.ROOT, "RESULTS.md")

FAILS = []


def val(res, block, metric, process=None):
    if process is None:
        return res["reference"][block][metric]
    return res["processes"][process]["values"][block][metric]


def claim(desc, got, want, tol=0.015):
    """want is what the prose says; got is what the data says."""
    ok = abs(got - want) <= max(tol, abs(want) * tol)
    print(f"  {'ok  ' if ok else 'FAIL'}  {desc:54s} doc {want:>9.3f}  data {got:>9.3f}")
    if not ok:
        FAILS.append(desc)


def main():
    res = json.load(open(os.path.join(WORK, "results_main.json"), encoding="utf-8"))
    doc = open(DOC, encoding="utf-8").read()
    print("figures quoted in RESULTS.md prose:\n")

    # 4.1 entropy
    claim("manuscript h2", val(res, "text", "h2 (char)"), 1.84)
    claim("fivecomp h2", val(res, "text", "h2 (char)", "fivecomp"), 1.86)
    claim("manual h2", val(res, "text", "h2 (char)", "manual"), 1.91)
    claim("naibbe latin h2", val(res, "text", "h2 (char)", "naibbe_latin"), 1.78)
    claim("naibbe italian h2", val(res, "text", "h2 (char)", "naibbe_italian"), 1.79)
    claim("selfcite h2", val(res, "text", "h2 (char)", "selfcite"), 2.31)
    claim("llull h2", val(res, "text", "h2 (char)", "llull"), 2.33)
    claim("abbrev h2", val(res, "text", "h2 (char)", "abbrev"), 3.22)
    claim("gibberish h2", val(res, "text", "h2 (char)", "gibberish"), 3.94)
    claim("natlang latin h2", val(res, "text", "h2 (char)", "natlang_latin"), 3.19)
    claim("subst h2", val(res, "text", "h2 (char)", "subst"), 3.19)
    claim("homophonic h2", val(res, "text", "h2 (char)", "subst_homophonic"), 4.74)
    claim("closest natural language h2 (italian)",
          val(res, "text", "h2 (char)", "natlang_italian"), 3.12)

    # 4.2 cross-word MI
    for p, want in [(None, 0.068), ("noise_floor", 0.068), ("fivecomp", 0.065),
                    ("natlang_italian", 0.056), ("manual", 0.049), ("abbrev", 0.024),
                    ("gibberish", 0.021), ("natlang_latin", 0.016),
                    ("selfcite", 0.010), ("naibbe_latin", 0.005),
                    ("grille_bigtable", 0.005), ("llull", 0.001)]:
        claim(f"cross-word MI {p or 'manuscript'}",
              val(res, "text", "cross-word MI", p), want, tol=0.0015)

    # 4.3 line block
    claim("manuscript m line-final %", val(res, "line", "m line-final %"), 66.97, 0.05)
    claim("noise floor m line-final %",
          val(res, "line", "m line-final %", "noise_floor"), 67.2, 0.05)
    claim("best process m line-final % (naibbe italian)",
          val(res, "line", "m line-final %", "naibbe_italian"), 17.3, 0.05)
    claim("manuscript gallows para-start lift",
          val(res, "line", "gallows para-start lift"), 73.34, 0.05)
    claim("noise floor gallows lift",
          val(res, "line", "gallows para-start lift", "noise_floor"), 74.6, 0.05)
    claim("selfcite gallows lift (most negative)",
          val(res, "line", "gallows para-start lift", "selfcite"), -5.81, 0.05)
    claim("fivecomp gallows lift",
          val(res, "line", "gallows para-start lift", "fivecomp"), 2.40, 0.05)
    claim("fivecomp gallows floor units",
          res["processes"]["fivecomp"]["floor_errors"]["line"]["gallows para-start lift"],
          10.0, 0.06)
    claim("fivecomp m line-final floor units",
          res["processes"]["fivecomp"]["floor_errors"]["line"]["m line-final %"],
          4.7, 0.06)

    # 4.4 abbreviation
    claim("abbrev h1", val(res, "text", "h1 (char)", "abbrev"), 4.22)
    claim("natlang latin h1", val(res, "text", "h1 (char)", "natlang_latin"), 3.97)
    claim("manuscript h1", val(res, "text", "h1 (char)"), 3.86)
    tuned = json.load(open(os.path.join(WORK, "tuned_main.json"), encoding="utf-8"))
    got = tuned["abbrev"]["cfg"]["allographs"]
    print(f"  {'ok  ' if got == 1 else 'FAIL'}  "
          f"{'tuner chose allographs=1':54s} doc {1:>9d}  data {got:>9d}")
    if got != 1:
        FAILS.append("abbrev allographs")

    # 4.5 grille
    claim("grille_bigtable TTR", val(res, "text", "TTR", "grille_bigtable"), 0.269, 0.01)
    claim("manuscript TTR", val(res, "text", "TTR"), 0.275, 0.01)
    claim("gibberish TTR", val(res, "text", "TTR", "gibberish"), 0.68, 0.01)
    claim("held-out tokens", res["ref_tokens"], 16436, 0.0001)

    # gate: ruler agreement claim in section 2
    worst = 0.0
    for (b, m), want in [(("text", "h2 (char)"), 1.842), (("struct", "len>=8 %"), 8.3)]:
        worst = max(worst, abs(val(res, b, m) - want) / want * 100)
    claim("ruler agreement with published values (%)", worst, 0.35, 0.3)

    print(f"\n{'ALL FIGURES CHECK OUT' if not FAILS else 'MISMATCHED: ' + ', '.join(FAILS)}")
    return 1 if FAILS else 0


if __name__ == "__main__":
    sys.exit(main())
